import { expect, test } from "@playwright/test";

test("Tree row actions keep visibility and lock independent from selection", async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/components/tree");
  await page.getByRole("checkbox", { name: "Tree prop showRowActions", exact: true }).check();
  const tree = page.locator(".preview-stage").getByRole("tree", { name: "Project files", exact: true });
  const layer = tree.getByRole("treeitem", { name: "Button.tsx", exact: true });
  const hide = layer.getByRole("button", { name: "Hide Button.tsx", exact: true });
  const lock = layer.getByRole("button", { name: "Lock Button.tsx", exact: true });
  const source = tree.getByRole("treeitem", { name: "Source", exact: true });
  await expect(hide).toHaveAttribute("tabindex", "-1");
  await source.focus();
  await source.press("ArrowDown");
  await page.keyboard.press("ArrowDown");
  await expect(layer).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(hide).toBeFocused();
  await page.keyboard.press("Space");
  await expect(hide).toHaveAttribute("aria-pressed", "true");
  await expect(layer).toHaveAttribute("aria-selected", "false");
  await page.keyboard.press("Tab");
  await expect(lock).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(lock).toHaveAttribute("aria-pressed", "true");
  await page.keyboard.press("ArrowDown");
  await expect(lock).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(layer).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(layer).toHaveAttribute("aria-selected", "true");
  await page.keyboard.press("ArrowDown");
  await expect(tree.getByRole("treeitem", { name: "Input.tsx", exact: true })).toBeFocused();
  await expect(lock).toHaveAttribute("tabindex", "-1");
  await page.evaluate(() => document.fonts.ready);
  await tree.screenshot({ path: info.outputPath("tree-row-actions.png") });
  await page.getByRole("checkbox", { name: "Tree prop readOnly", exact: true }).check();
  await expect(lock).toBeDisabled();
});
