test("DescriptionList responds to its container and keeps tight term/value grouping",async({page})=>{
  await page.setViewportSize({width:1440,height:1000});
  await page.goto("/components/description-list");
  const list=page.locator(".workbench-stage dl");
  await expect(list.locator("dt")).toHaveText(["Project","Version","Owner"]);
  const rects=()=>list.evaluate(el=>{const dt=el.querySelector('dt')!.getBoundingClientRect(),dd=el.querySelector('dd')!.getBoundingClientRect(),next=el.querySelectorAll('dt')[1].getBoundingClientRect();return{termTop:dt.top,termBottom:dt.bottom,valueTop:dd.top,pitch:next.top-dt.top};});
  const inline=await rects();expect(inline.valueTop).toBeCloseTo(inline.termTop,1);
  await chooseSelectOption(page.getByRole("combobox",{name:"DescriptionList prop density"}),"comfortable");
  expect((await rects()).pitch).toBeGreaterThan(inline.pitch+6);
  await list.evaluate(el=>{el.style.width="18rem";});
  const stacked=await rects();expect(stacked.valueTop-stacked.termBottom).toBeCloseTo(4,1);
  await list.evaluate(el=>{el.style.width="100%";});
  await chooseSelectOption(page.getByRole("combobox",{name:"DescriptionList prop layout"}),"stacked");
  expect((await rects()).valueTop).toBeGreaterThan((await rects()).termBottom);
  await page.getByRole("checkbox",{name:"DescriptionList prop longValue"}).check();
  await page.setViewportSize({width:320,height:900});
  await page.evaluate(()=>{document.documentElement.style.fontSize="24px";document.documentElement.dir="rtl";});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});

test("DescriptionList keeps value actions on a shared edge and preserves long values", async ({page, context}, info) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.goto("/components/description-list");
  await page.getByRole("checkbox", {name:"DescriptionList prop showActions"}).check();
  const list = page.locator(".preview-stage .flood-description-list");
  const copyVersion = list.getByRole("button", {name:"Copy version",exact:true});
  const copyOwner = list.getByRole("button", {name:"Copy owner",exact:true});
  const [version, owner] = await Promise.all([copyVersion.boundingBox(),copyOwner.boundingBox()]);
  expect(version!.x + version!.width).toBeCloseTo(owner!.x + owner!.width, 0);
  const value = (await list.locator(".flood-description-list__value").first().textContent())!.trim();
  await copyVersion.press("Enter");
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe(value);
  await expect(copyVersion.or(list.getByRole("button", {name:/^Copied/}))).toBeFocused();

  await page.getByRole("checkbox", {name:"DescriptionList prop constrainWidth"}).check();
  await page.getByRole("checkbox", {name:"DescriptionList prop longValue"}).check();
  await chooseSelectOption(page.getByRole("combobox", {name:"DescriptionList prop layout"}), "columns");
  await page.evaluate(() => {document.documentElement.dir = "rtl"; document.documentElement.style.fontSize = "24px";});
  const row = list.locator(".flood-description-list__item").last();
  await expect(row.locator("dd")).toContainText("design-system-maintainers@a-very-long-example-company.example");
  await expect(copyOwner).toBeVisible();
  const [term, longValue] = await Promise.all([row.locator("dt").boundingBox(),row.locator(".flood-description-list__value").boundingBox()]);
  expect(term!.y).toBeCloseTo(longValue!.y, 0);
  expect(await row.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);

  await page.evaluate(() => {document.documentElement.dir = "ltr"; document.documentElement.style.fontSize = "";});
  await page.getByRole("checkbox", {name:"DescriptionList prop truncateValue"}).check();
  const clipped = row.locator(".flood-truncated-text");
  await expect(clipped).toHaveAttribute("tabindex","0");
  expect((await clipped.boundingBox())!.height).toBeLessThan(longValue!.height);
  const action = (await copyOwner.boundingBox())!;
  const line = (await clipped.boundingBox())!;
  expect(Math.abs(action.y + action.height / 2 - line.y - line.height / 2)).toBeLessThan(3);
  await list.screenshot({path:info.outputPath("description-list-truncated.png")});
  await clipped.focus();
  const tooltip = page.getByRole("tooltip");
  const fullValue = "design-system-maintainers@a-very-long-example-company.example";
  await expect(tooltip).toHaveText(fullValue);
  await page.locator(".preview-stage").screenshot({path:info.outputPath("description-list-disclosure.png")});
  await page.keyboard.press("Escape");
  await expect(tooltip).toBeHidden();
  await page.keyboard.press("Tab");
  await expect(copyOwner).toBeFocused();
  await page.keyboard.press("Enter");
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe(fullValue);
});

test("a stacked description item uses the full value width without moving the other facts", async ({page}, info) => {
  await page.setViewportSize({width:1440,height:940});
  await page.goto("/components/description-list");
  await chooseSelectOption(page.getByRole("combobox",{name:"DescriptionList prop layout"}),"columns");
  for (const name of ["constrainWidth", "longValue", "showActions"]) {
    await page.getByRole("checkbox",{name:`DescriptionList prop ${name}`}).check();
  }
  const list = page.locator('.preview-stage dl[aria-label="Project details"]');
  const owner = list.locator("dd").last();
  const term = list.locator("dt").last();
  const before = (await owner.boundingBox())!;
  const peer = (await list.locator("dd").first().boundingBox())!;
  await page.getByRole("checkbox",{name:"DescriptionList prop stackOwner"}).check();
  const bounds = (await owner.boundingBox())!;
  const termBounds = (await term.boundingBox())!;
  expect(bounds.x).toBeCloseTo(termBounds.x,0);
  expect(bounds.y).toBeGreaterThan(termBounds.y+termBounds.height);
  expect(bounds.width).toBeGreaterThan(before.width);
  expect(bounds.height).toBeLessThan(before.height);
  expect((await list.locator("dd").first().boundingBox())!.width).toBe(peer.width);
  await expect(list.getByRole("button",{name:"Copy owner"})).toBeInViewport();
  await list.screenshot({path:info.outputPath("description-mixed-columns.png")});
  await page.getByRole("checkbox",{name:"DescriptionList prop constrainWidth"}).uncheck();
  await chooseSelectOption(page.getByRole("combobox",{name:"DescriptionList prop layout"}),"grid");
  expect((await owner.boundingBox())!.width).toBeCloseTo((await list.boundingBox())!.width,0);
  await expect(list.locator("dt")).toHaveText(["Project","Version","Owner"]);
});

test("Table preserves its caption, native headers and keyboard horizontal scrolling",async({page})=>{
  await page.setViewportSize({width:390,height:900});
  await page.goto("/components/table");
  const stage=page.locator(".workbench-stage"),table=stage.getByRole("table",{name:"Workspace projects",exact:true});
  const viewport=stage.getByRole("region",{name:"Workspace projects",exact:true});
  await expect(table.getByRole("columnheader")).toHaveCount(4);
  await expect(table.getByRole("rowheader",{name:"Flood",exact:true})).toHaveAttribute("scope","row");
  await expect.poll(()=>viewport.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true);
  await viewport.focus();await page.keyboard.press("ArrowRight");
  await expect.poll(()=>viewport.evaluate(el=>Math.abs(el.scrollLeft))).toBeGreaterThan(0);
  await page.getByRole("checkbox",{name:"Table prop hideCaption"}).check();
  await expect(table).toBeVisible();
  await expect(table.locator("caption")).toHaveClass("flood-visually-hidden");
  await page.getByRole("checkbox",{name:"Table prop empty"}).check();
  await expect(table.getByRole("cell",{name:"No projects yet."})).toHaveAttribute("colspan","4");
  await expect(table.locator("tfoot")).toHaveCount(0);
  await page.getByRole("checkbox",{name:"Table prop empty"}).uncheck();
  await expect(table.getByRole("cell",{name:"50 GB",exact:true})).toBeAttached();
  await chooseSelectOption(page.getByRole("combobox",{name:"Table prop density"}),"compact");
  await page.evaluate(()=>{document.documentElement.style.fontSize="24px";document.documentElement.dir="rtl";});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await expect(table.locator('[data-numeric]').first()).toHaveCSS("text-align","end");
});

